"use client";

import { School } from "@/lib/schools";

/* Brand values mirrored from the --green-* scale in globals.css. jsPDF and
   canvas render outside the DOM, so they cannot resolve CSS variables; these
   must be kept in step with that scale by hand. */
const GREEN_900: [number, number, number] = [20, 52, 42];
const GREEN_700: [number, number, number] = [31, 77, 58];
const GREEN_500: [number, number, number] = [47, 122, 87];
const GREEN_300: [number, number, number] = [143, 194, 165];
const INK: [number, number, number] = [14, 26, 21];


/**
 * Clean PDF of every school marked Applying, for sharing with an advisor.
 * jsPDF is imported on click so it never lands in the initial page bundle.
 */
export default function ExportTargetList({
  schools,
  userName,
}: {
  schools: School[];
  userName: string;
}) {
  async function exportPdf() {
    const { jsPDF } = await import("jspdf");
    const doc = new jsPDF({ unit: "pt", format: "letter" });
    const M = 56;
    let y = M;

    const today = new Date();
    const MONTHS = ["JAN","FEB","MAR","APR","MAY","JUN","JUL","AUG","SEP","OCT","NOV","DEC"];
    const stamp = `${String(today.getDate()).padStart(2, "0")} ${MONTHS[today.getMonth()]} ${today.getFullYear()}`;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(16);
    doc.text("Target School List", M, y);
    y += 18;

    doc.setFont("courier", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...GREEN_500);
    doc.text(`${userName} / ${stamp} / ${schools.length} SCHOOLS`, M, y);
    doc.setTextColor(...INK);
    y += 16;

    doc.setDrawColor(...GREEN_300);
    doc.line(M, y, 612 - M, y);
    y += 22;

    // Column headings
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.text("SCHOOL", M, y);
    doc.text("ST", 388, y);
    doc.text("AVG GPA", 424, y);
    doc.text("AVG MCAT", 492, y);
    y += 6;
    doc.setDrawColor(...GREEN_300);
    doc.line(M, y, 612 - M, y);
    y += 14;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);

    for (const s of schools) {
      if (y > 720) {
        doc.addPage();
        y = M;
      }
      const name = s.name.length > 52 ? `${s.name.slice(0, 51)}…` : s.name;
      doc.text(name, M, y);
      doc.setFont("courier", "normal");
      doc.setFontSize(9);
      doc.text(s.state, 388, y);
      doc.text(s.avgGpa === null ? "NR" : s.avgGpa.toFixed(2), 424, y);
      doc.text(s.avgMcat === null ? "NR" : String(s.avgMcat), 492, y);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(10);
      y += 8;
      doc.setDrawColor(...GREEN_300);
      doc.line(M, y, 612 - M, y);
      y += 14;
    }

    doc.setFont("courier", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...GREEN_500);
    doc.text("Generated by ClinicLog MD  /  NR = average not published by the school", M, 756);

    doc.save("target-school-list.pdf");
  }

  if (schools.length === 0) return null;

  return (
    <button
      onClick={exportPdf}
      className="btn-ghost text-xs font-semibold"
      style={{ padding: "8px var(--sp-2)" }}
    >
      Export target list ({schools.length})
    </button>
  );
}
