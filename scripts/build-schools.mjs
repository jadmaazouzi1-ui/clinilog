// Builds src/lib/schools.ts and docs/data/school-sources.csv from the
// research results (one JSON file per batch). Rules, from SOURCES_AUDIT.md:
//   - A figure counts only if it was read on the school's own website.
//   - Figures for a class that entered before 2022, or with no stated year,
//     are kept in the CSV for the record but not shown in the app.
//   - Implausible values (GPA outside 2.5 to 4.0, MCAT outside 490 to 528)
//     are dropped and flagged.
//   - School names stay as they were, because saved schools are stored by
//     name; the official name is kept in the CSV.
// Usage: node scripts/build-schools.mjs <resultsDir> <originalListJson>

import fs from "node:fs";
import path from "node:path";

const [, , dir, listPath] = process.argv;
const list = JSON.parse(fs.readFileSync(listPath, "utf8")); // [group, name, state, gpa, mcat]
const results = new Map();
const filled = (r) => (r.gpa !== null ? 1 : 0) + (r.mcat !== null ? 1 : 0);
for (const f of fs.readdirSync(dir).filter((f) => /^result-\d+\.json$/.test(f))) {
  for (const r of JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))) results.set(r.inputName, r);
}
// Second-pass results replace the first pass only when they found more.
for (const f of fs.readdirSync(dir).filter((f) => /^result-retry-\d+\.json$/.test(f))) {
  for (const r of JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))) {
    const prev = results.get(r.inputName);
    if (!prev || filled(r) > filled(prev) || (filled(r) === filled(prev) && !prev.sourceUrl && r.sourceUrl)) results.set(r.inputName, r);
  }
}

const MIN_YEAR = 2022;
// Figures held back after review, with the reason recorded in the CSV.
const OVERRIDES = {
  "Creighton University School of Medicine": { statKind: null, why: "No mean or median label: the page gives a median GPA but a mean MCAT." },
  "Baylor College of Medicine": { gpa: null, why: "GPA not shown: the post does not say overall or science, and Baylor's 2024 post reported a science GPA." },
};
const rows = [];
const flags = [];
for (const [group, rawName, state] of list) {
  // The extracted list keeps source escapes such as \u2013; decode for display.
  const name = JSON.parse(`"${rawName.replace(/"/g, '\\"')}"`);
  const r = results.get(rawName) ?? results.get(name);
  if (!r) { flags.push(`no result: ${rawName}`); }
  let gpa = r?.gpa ?? null, mcat = r?.mcat ?? null;
  const ov = OVERRIDES[name];
  if (ov && "gpa" in ov) gpa = ov.gpa;
  if (ov) flags.push(`override: ${name}: ${ov.why}`);
  if (gpa !== null && (gpa < 2.5 || gpa > 4)) { flags.push(`implausible GPA ${gpa}: ${name}`); gpa = null; }
  if (mcat !== null && (mcat < 490 || mcat > 528)) { flags.push(`implausible MCAT ${mcat}: ${name}`); mcat = null; }
  // Accepted-applicant figures are not the entering class; the agents kept a
  // few with a flag in the notes. They are recorded but not shown.
  const acceptedOnly = /\baccepted (students|applicants|candidates)\b/i.test(r?.notes ?? "") && (gpa !== null || mcat !== null);
  if (acceptedOnly) flags.push(`accepted-applicant figures not shown: ${name}`);
  const year = acceptedOnly ? null : r?.enteringYear ?? null;
  const current = year !== null && year >= MIN_YEAR && !!r?.sourceUrl;
  rows.push({
    group, name,
    state: r?.state && (/^[A-Z]{2}$/.test(r.state)) ? r.state : state,
    shownGpa: current ? gpa : null,
    shownMcat: current ? mcat : null,
    statKind: current && (gpa !== null || mcat !== null) ? (ov && "statKind" in ov ? ov.statKind : r.statKind ?? null) : null,
    enteringYear: current && (gpa !== null || mcat !== null) ? year : null,
    sourceUrl: r?.sourceUrl ?? null,
    checked: r?.checked ?? "2026-11-18",
    officialName: r?.officialName ?? "",
    foundGpa: r?.gpa ?? "", foundMcat: r?.mcat ?? "", foundYear: year ?? "",
    notes: ((ov ? ov.why + " " : "") + (r?.notes ?? "")).replace(/\s+/g, " "),
  });
}

const js = (v) => (v === null ? "null" : JSON.stringify(v));
const line = (r) =>
  `  { name: ${js(r.name)}, state: ${js(r.state)}, avgGpa: ${r.shownGpa === null ? "null" : Number(r.shownGpa).toFixed(2)}, avgMcat: ${js(r.shownMcat)}, statKind: ${js(r.statKind)}, enteringYear: ${js(r.enteringYear)}, sourceUrl: ${js(r.sourceUrl)}, checked: ${js(r.checked)} },`;

const block = (g, label) => rows.filter((r) => r.group === g).map(line).join("\n");
const out = `/* Medical schools. Generated by scripts/build-schools.mjs from research
   done on ${new Date().toISOString().slice(0, 10)}; do not edit by hand. The full record, including
   figures found but not shown, is docs/data/school-sources.csv.

   Every GPA and MCAT figure was read on the school's own website, on the
   page in sourceUrl, and describes the class that entered in enteringYear.
   avgGpa and avgMcat are null when the school does not publish the figure,
   or publishes it only for a class that entered before ${MIN_YEAR}. Null means
   "not reported", never zero: such schools are left out of GPA and MCAT
   matching and the gap check. statKind says whether the school reports a
   mean or a median. See SOURCES_AUDIT.md. */

export type Degree = "MD" | "DO" | "Caribbean";

export interface School {
  name: string;
  state: string;
  avgGpa: number | null;
  avgMcat: number | null;
  statKind: "mean" | "median" | null;
  enteringYear: number | null;
  sourceUrl: string | null;
  checked: string;
  degree: Degree;
}

type Raw = Omit<School, "degree">;

const MD_RAW: Raw[] = [
${block("MD")}
];
export const MD_SCHOOLS: School[] = MD_RAW.map((s) => ({ ...s, degree: "MD" }));

const DO_RAW: Raw[] = [
${block("DO")}
];
export const DO_SCHOOLS: School[] = DO_RAW.map((s) => ({ ...s, degree: "DO" }));

const CARIBBEAN_RAW: Raw[] = [
${block("CA")}
];
export const CARIBBEAN_SCHOOLS: School[] = CARIBBEAN_RAW.map((s) => ({ ...s, degree: "Caribbean" }));

export const SCHOOLS: School[] = [...MD_SCHOOLS, ...DO_SCHOOLS, ...CARIBBEAN_SCHOOLS];

export const ALL_STATES = [...new Set(SCHOOLS.map((s) => s.state))].sort();

/** True when the school publishes both figures and can be compared against. */
export function hasPublishedStats(s: School): boolean {
  return s.avgGpa !== null && s.avgMcat !== null;
}
`;
// En dashes in names are written as \u2013 escapes, as the source always has.
fs.writeFileSync("src/lib/schools.ts", out.replace(/\u2014/g, ",").replace(/\u2013/g, "\\u2013"));

const csvCell = (v) => `"${String(v ?? "").replace(/"/g, '""').replace(/\u2014/g, ",")}"`;
const head = ["group", "name", "official_name", "state", "gpa_found", "mcat_found", "entering_year", "stat_kind", "shown_gpa", "shown_mcat", "source_url", "checked", "notes"];
const csv = [head.join(",")].concat(rows.map((r) => [r.group, r.name, r.officialName, r.state, r.foundGpa, r.foundMcat, r.foundYear, r.statKind ?? "", r.shownGpa ?? "", r.shownMcat ?? "", r.sourceUrl ?? "", r.checked, r.notes].map(csvCell).join(",")));
fs.mkdirSync("docs/data", { recursive: true });
fs.writeFileSync("docs/data/school-sources.csv", csv.join("\n") + "\n");

const both = rows.filter((r) => r.shownGpa !== null && r.shownMcat !== null).length;
const partial = rows.filter((r) => (r.shownGpa === null) !== (r.shownMcat === null)).length;
console.log(`schools: ${rows.length}, both shown: ${both}, one shown: ${partial}, none shown: ${rows.length - both - partial}`);
for (const f of flags) console.log("FLAG", f);
